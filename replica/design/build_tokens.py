#!/usr/bin/env python3
"""Generate tokens.css (CSS variables, light + dark) and tailwind.theme.css (Tailwind v4 @theme)
from tokens.json and tokens.dark.json. Re-run after any token change:  python3 build_tokens.py"""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
L = json.load(open(os.path.join(H, "tokens.json")))
D = json.load(open(os.path.join(H, "tokens.dark.json")))

def colors(c, ind="  "):
    return "\n".join(f"{ind}--color-{k}: {v};" for k, v in c["color"].items())

out = ["/* GENERATED by build_tokens.py from tokens.json + tokens.dark.json. Do not edit by hand. */", ":root {", colors(L)]
out += [f"  --font-{k}: {v};" for k, v in L["font"].items()]
for k, t in L["type"].items():
    out += [f"  --text-{k}: {t['size']/16:g}rem;", f"  --text-{k}--line-height: {t['line']/16:g}rem;", f"  --text-{k}--font-weight: {t['weight']};"]
out += [f"  --space-{i}: {v/16:g}rem;" for i, v in enumerate(L["space"])]
out += [f"  --radius-{k}: {v}px;" for k, v in L["radius"].items()]
out += [f"  --control-{k}: {v/16:g}rem;" for k, v in L["control"].items()]
out += [f"  --layout-{k}: {v}px;" for k, v in L["layout"].items() if not isinstance(v, dict)]
out += [f"  --shadow-{k}: {v};" for k, v in L["shadow"].items()]
out += [f"  --motion-{k}: {v};" for k, v in L["motion"].items() if k != "reduced"]
out += ["  color-scheme: light;", "}"]
dark = colors(D, "    ") + "\n" + "\n".join(f"    --shadow-{k}: {v};" for k, v in D["shadow"].items())
out += ["@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {", dark, "    color-scheme: dark;", "  }", "}",
        ":root[data-theme=\"dark\"] {", dark.replace("    ", "  "), "  color-scheme: dark;", "}",
        "@media (prefers-reduced-motion: reduce) {", "  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }", "}"]
open(os.path.join(H, "tokens.css"), "w").write("\n".join(out) + "\n")

# Tailwind v4: map the variables into the theme so components write bg-surface text-muted, never hex.
tw = ["/* GENERATED by build_tokens.py. Import after tailwindcss:  @import \"tailwindcss\"; @import \"./tokens.css\"; @import \"./tailwind.theme.css\"; */",
      "@theme inline {"]
tw += [f"  --color-{k}: var(--color-{k});" for k in L["color"]]
tw += [f"  --font-{k}: var(--font-{k});" for k in L["font"]]
for k in L["type"]:
    tw += [f"  --text-{k}: var(--text-{k});", f"  --text-{k}--line-height: var(--text-{k}--line-height);", f"  --text-{k}--font-weight: var(--text-{k}--font-weight);"]
tw += [f"  --radius-{k}: var(--radius-{k});" for k in L["radius"]]
tw += [f"  --shadow-{k}: var(--shadow-{k});" for k in L["shadow"]]
tw += ["  --spacing: 0.25rem;  /* 4px base: p-4 = 16px */",
       f"  --breakpoint-sm: {L['layout']['breakpoints']['sm']/16:g}rem;", f"  --breakpoint-md: {L['layout']['breakpoints']['md']/16:g}rem;",
       f"  --breakpoint-lg: {L['layout']['breakpoints']['lg']/16:g}rem;", f"  --breakpoint-xl: {L['layout']['breakpoints']['xl']/16:g}rem;", "}"]
open(os.path.join(H, "tailwind.theme.css"), "w").write("\n".join(tw) + "\n")
print("wrote tokens.css, tailwind.theme.css")
